export const defaultCatalogueCategories = [...new Set(defaultRequestTemplates.map((item) => item.category))].sort((a, b) => a.localeCompare(b))

export function catalogueTemplateItem(template) {
  return {
    id: template.id,
    title: template.title,
    category: template.category,
    description: template.description,
    kind: 'request-form',
    requestType: template.requestType,
    service: template.service,
    team: template.team,
    approval: template.approval || 'none',
    approvalThreshold: template.approvalThreshold ?? null,
    visibility: template.visibility || 'portal',
    vendor: '',
    sku: '',
    priceMode: 'none',
    oneOffPrice: 0,
    monthlyPrice: 0,
    currency: 'GBP',
    workflow: template.workflow || `${template.service || 'Service'} fulfilment`,
    workflowTasks: Array.isArray(template.workflowTasks) ? template.workflowTasks : [],
    formSchema: Array.isArray(template.fields) ? template.fields : [],
    options: [],
    optionsCount: Array.isArray(template.fields) ? template.fields.filter((field) => field.type !== 'section').length : 0,
    source: template.source || source(template.id.toLowerCase()),
    active: true,
  }
}

export function defaultCatalogueState() {
  const items = defaultRequestTemplates.map(catalogueTemplateItem)
  return { items, categories: defaultCatalogueCategories }
}
